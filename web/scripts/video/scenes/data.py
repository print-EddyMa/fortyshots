#!/usr/bin/env python3
"""Numbers for the explainer scenes, read from the repository's result files (stdlib only).

    python3 web/scripts/video/scenes/data.py            -> web/scripts/video/scenes/data.js

Every number a scene shows comes from here; the scenes never hard-code one. Sources:
  results/hero.json      the landing hero (id, metal, E_CO2, E_H2O)
  results/pools.json     DFT labels of the 3,000 MOFs (water-wins share; a typical water-wins example)
  results/atlas.json     t-SNE positions of the 3,000 MOFs, pool membership, hit flags
  results/results.json   budget, arms with 95% intervals, claim counts
  docs/data/runs/<showcase>/events.jsonl   the showcase run's 40 picks, hits and a line of model reasoning
  README.md              the DFlash A/B (decode tok/s with and without Meta's drafter), measured on the Mac
                         (doctor/*-bench-*.json on branch runs-mac)
record-broll.mjs runs this before it records the scenes.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]


def load(p: str):
    return json.loads((ROOT / p).read_text(encoding="utf-8"))


def showcase_run() -> tuple[str, list[dict]]:
    idx = load("docs/data/runs/index.json")
    run = next((r for r in idx if r.get("showcase")), None) or next((r for r in idx if r.get("arm") == "A5" and r.get("pool") == "P1"), idx[0])
    rid = run["run_id"]
    ev = [json.loads(x) for x in (ROOT / "docs/data/runs" / rid / "events.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    return rid, ev


def dflash() -> dict:
    """README 'DFlash drafter A/B' row: '3.0 → 6.8 tok/s ..., 68% of drafted tokens accepted'."""
    md = (ROOT / "README.md").read_text(encoding="utf-8")
    m = re.search(r"DFlash drafter A/B\s*\|\s*([\d.]+)\s*→\s*([\d.]+)\s*tok/s[^|]*?(\d+)% of drafted tokens accepted", md)
    if not m:
        sys.exit("data.py: README.md has no 'DFlash drafter A/B' row")
    base, fast, acc = float(m.group(1)), float(m.group(2)), int(m.group(3))
    chip = re.search(r"\|\s*Machine\s*\|\s*([^|]+?)\s*\|", md)
    return {
        "base_tps": base,
        "dflash_tps": fast,
        "accept_pct": acc,
        "speedup": round(fast / base, 1),
        "machine": (chip.group(1).split(",")[0] + ", " + chip.group(1).split(",")[1].strip()) if chip else "MacBook Pro, Apple M4",
    }


def main() -> int:
    hero = load("results/hero.json")
    pools = load("results/pools.json")["pools"]
    atlas = load("results/atlas.json")
    res = load("results/results.json")
    rid, ev = showcase_run()

    allm = [m for v in pools.values() for m in v]
    water = sum(1 for m in allm if m["E_H2O"] < m["E_CO2"])
    water_pct = round(100 * water / len(allm))

    pool_id = next(e["payload"].get("pool") for e in ev if e["kind"] == "summary") if any(e["kind"] == "summary" for e in ev) else "P1"
    pool = {m["id"]: m for m in pools[pool_id]}
    picks_by_round: list[list[str]] = []
    hit_ids: list[str] = []
    for e in ev:
        if e["kind"] == "dft_order":
            picks_by_round.append(list(e["payload"]["ids"]))
        if e["kind"] == "dft_result":
            hit_ids += [r["id"] for r in e["payload"]["results"] if r.get("hit")]

    # a typical "water wins" material from the run's first purchase: CO2 binds, but water binds harder
    first = next(e for e in ev if e["kind"] == "dft_result")["payload"]["results"]
    ww = [r for r in first if r["E_H2O"] < r["E_CO2"]]
    ww.sort(key=lambda r: r["E_CO2"])
    water_ex = ww[0]
    water_ex["metals"] = pool[water_ex["id"]]["metals"]

    # the model's own words for the DFlash token race: the Director's reasoning in round 2, without the
    # paragraph that echoes its instructions ("ROLE: ...")
    reason_ev = next(e for e in ev if e["kind"] == "reasoning" and e.get("role") == "director" and e.get("round") == 2)
    paras = [p for p in re.split(r"\n\s*\n", reason_ev["payload"]["text"]) if p.strip() and not p.lstrip().startswith("ROLE:")]
    words = [w for w in re.sub(r"\s+", " ", " ".join(paras)).split(" ") if w][:90]

    pts = atlas["points"]
    arms = {a["arm"]: a for a in res["arms"]}

    def arm(k, label, note):
        a = arms[k]
        return {"arm": k, "label": label, "note": note, "mean": round(a["hits_mean"], 1), "lo": a["hits_ci"][0], "hi": a["hits_ci"][1], "n_runs": a["n_runs"]}

    data = {
        "source": "generated by web/scripts/video/scenes/data.py from results/*.json, README.md and the showcase run",
        "humidity": {
            "water_pct": water_pct,
            "water_n": water,
            "n": len(allm),
            "hero": {"id": hero["id"], "metal": hero["metals"], "E_CO2": hero["E_CO2"], "E_H2O": hero["E_H2O"], "oms": True},
            "water_example": {"id": water_ex["id"], "metal": water_ex["metals"], "E_CO2": water_ex["E_CO2"], "E_H2O": water_ex["E_H2O"]},
        },
        "bottleneck": {
            "n_all": atlas["n"],
            "pool": pool_id,
            "pool_n": len(pools[pool_id]),
            "pool_hits": sum(1 for m in pools[pool_id] if m["hit"]),
            "budget": res["budget"],
            "run_id": rid,
            "x": pts["x"],
            "y": pts["y"],
            "ids": pts["id"],
            "in_pool": [p == pool_id for p in pts["pool"]],
            "hit": pts["hit"],
            "picks_by_round": picks_by_round,
            "found": hit_ids,
        },
        "loop": {"budget": res["budget"], "rounds": len(picks_by_round) or 4, "batch": res["budget"] // (len(picks_by_round) or 4)},
        "dflash": {**dflash(), "words": words, "words_from": f"{rid}, Director reasoning, round 2"},
        "result": {
            "budget": res["budget"],
            "status": res["status"],
            "arms": [
                arm("A0", "Random picks", "random"),
                arm("A3", "Machine-learning baseline", "random forest"),
                arm("A5", "fortyshots", "Muse Glimmer agent"),
                arm("A2", "Best simple method", "MACE-greedy"),
            ],
        },
    }
    out = HERE / "data.js"
    out.write_text("// generated by data.py; do not edit\nwindow.SCENE_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"scenes: wrote {out.relative_to(ROOT)} (water wins {water_pct}% of {len(allm)}, pool {pool_id}, {sum(len(r) for r in picks_by_round)} picks, {len(hit_ids)} hit(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
